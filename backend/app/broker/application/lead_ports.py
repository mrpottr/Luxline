"""Provider interfaces for broker lead workflows."""

from typing import Any, Protocol


class LeadProvider(Protocol):
    def is_broker_approved(self) -> bool: ...
    def sync_public_inquiries(self) -> None: ...
    def list_leads(self, *, assigned_member_id: int | None, stage: str | None, limit: int, offset: int, sort: str) -> list[Any]: ...
    def get_lead(self, lead_id: int) -> Any | None: ...
    def assign_lead(self, lead_id: int, member_id: int) -> Any | None: ...
    def update_stage(self, lead_id: int, stage: str) -> Any | None: ...
    def update_spam_flag(self, lead_id: int, spam_flag: bool) -> Any | None: ...
    def add_activity(self, *, lead_id: int, actor_user_id: int, activity_type: str, body: str, due_at=None, idempotency_key: str | None = None) -> Any | None: ...
    def list_activities(self, lead_id: int, limit: int, offset: int) -> list[Any] | None: ...
    def add_message(self, *, lead_id: int, sender_type: str, sender_user_id: int | None, body: str, idempotency_key: str) -> Any | None: ...
    def list_messages(self, lead_id: int, limit: int, offset: int) -> list[Any] | None: ...
    def list_buyer_leads(self, buyer_id: int, limit: int, offset: int) -> list[Any]: ...
    def get_buyer_lead(self, lead_id: int, buyer_id: int) -> Any | None: ...
    def list_buyer_messages(self, lead: Any, limit: int, offset: int) -> list[Any]: ...
    def add_buyer_message(self, *, lead: Any, buyer_id: int, body: str, idempotency_key: str) -> Any: ...
    def list_templates(self, limit: int, offset: int) -> list[Any]: ...
    def create_template(self, *, title: str, body: str, created_by: int, idempotency_key: str) -> Any: ...
