"""Provider interfaces for broker plans, credits, and promotions."""

from datetime import datetime
from typing import Any, Protocol


class MonetizationProvider(Protocol):
    def is_broker_approved(self) -> bool: ...
    def get_active_subscription(self) -> Any | None: ...
    def get_active_plans(self, *, limit: int, offset: int, sort: str) -> list[Any]: ...
    def get_plan(self, code: str) -> Any | None: ...
    def get_wallet_balance(self) -> int: ...
    def list_ledger(self, *, limit: int, offset: int) -> list[Any]: ...
    def list_promotions(self, *, status: str | None, limit: int, offset: int) -> list[Any]: ...
    def get_promotion_context(self, *, listing_id: int, actor_user_id: int, restrict_to_assigned_agent: bool) -> dict[str, Any] | None: ...
    def create_promotion_transaction(self, *, payload: dict[str, Any], cost: int, actor_user_id: int, idempotency_key: str, payload_digest: str) -> Any: ...
    def purchase_credits_transaction(self, *, package: dict[str, Any], payment_reference: str, actor_user_id: int, idempotency_key: str, payload_digest: str) -> Any: ...
    def subscribe_transaction(self, *, plan: Any, payment_reference: str, idempotency_key: str, payload_digest: str) -> Any: ...


class PaymentProvider(Protocol):
    def charge(self, *, organization_id: int, amount: str, currency: str, idempotency_key: str) -> str: ...
