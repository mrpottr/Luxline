"""Provider interfaces used by broker listing use cases."""

from typing import Any, Protocol


class ListingProvider(Protocol):
    def is_broker_approved(self) -> bool: ...
    def list_categories(self) -> list[str]: ...
    def list_listings(self, *, filters: dict[str, Any], limit: int, offset: int, sort: str) -> list[Any]: ...
    def create_listing(self, *, payload: dict[str, Any], user_id: int, idempotency_key: str) -> Any: ...
    def update_listing(self, *, listing_id: int, changes: dict[str, Any], actor_user_id: int, restrict_to_assigned_agent: bool) -> Any | None: ...
    def set_listing_status(self, *, listing_id: int, status: str, actor_user_id: int, restrict_to_assigned_agent: bool) -> Any | None: ...
    def get_publish_context(self, *, listing_id: int, actor_user_id: int, restrict_to_assigned_agent: bool) -> dict[str, Any] | None: ...
    def list_revisions(self, *, listing_id: int, actor_user_id: int, restrict_to_assigned_agent: bool, limit: int) -> list[Any] | None: ...


class ListingAccessProvider(Protocol):
    def find_owned_organization(self, *, user_id: int) -> int | None: ...
    def find_member_role(self, *, organization_id: int, user_id: int) -> Any | None: ...
    def list_member_roles(self, *, user_id: int, limit: int) -> list[tuple[int, Any]]: ...
    def organization_exists(self, *, organization_id: int) -> bool: ...


class RateLimiter(Protocol):
    def consume(self, key: str, *, maximum: int, window_seconds: int) -> bool: ...
