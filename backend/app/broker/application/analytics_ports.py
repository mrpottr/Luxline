"""Provider contract for broker analytics reads and rollup writes."""

from datetime import date
from typing import Any, Protocol


class AnalyticsProvider(Protocol):
    def is_public_listing_eligible(self, listing_id: int) -> bool: ...
    def record_public_listing_event(self, listing_id: int, event_type: str) -> bool: ...
    def is_broker_approved(self) -> bool: ...
    def capture_source_events(self, *, start: date, end: date) -> None: ...
    def list_events(self, *, start: date, end: date, listing_id: int | None, agent_id: int | None) -> list[Any]: ...
    def list_daily_rollups(self, *, start: date, end: date, listing_id: int | None, agent_id: int | None) -> list[Any]: ...
    def save_daily_rollups(self, rollups: list[dict[str, Any]]) -> None: ...
