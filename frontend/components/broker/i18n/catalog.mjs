export function resolveBrokerLocale(preferred) {
  const value = String(preferred || '').toLowerCase();
  if (value.startsWith('si')) return 'si';
  if (value.startsWith('ta')) return 'ta';
  return 'en';
}

export function translateBrokerMessage(message, locale = 'en') {
  const language = brokerCatalog[resolveBrokerLocale(locale)];
  return language[message] ?? brokerCatalog.en[message] ?? message;
}
